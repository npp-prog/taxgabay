/**
 * Generates supabase/seed-issuances.sql from the bundled issuance list.
 * Rows go in as DRAFTS (the CPA reviews and publishes them in /admin) and never
 * overwrite existing rows, so admin edits are kept.  Run: pnpm db:seed-issuances
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { seedIssuanceLinks, seedIssuances } from "../src/issuances";

const out = resolve(dirname(fileURLToPath(import.meta.url)), "../../../supabase/seed-issuances.sql");
const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;

const rows = seedIssuances.map(
  (i) =>
    `  (${q(i.slug)}, ${q(i.type)}, ${q(i.number)}, ${q(i.title)}, ${q(i.date_issued)}, ${q(i.effectivity_date)}, ${arr(i.tax_types)}, ${arr(i.topics)}, ${q(i.summary_plain)}, ${q(i.status)}, ${q(i.source_url)}, true)`,
);
const links = seedIssuanceLinks.map(
  (l) =>
    `insert into public.issuance_links (from_id, to_id, relation)\n  select f.id, t.id, ${q(l.relation)} from public.issuances f, public.issuances t where f.slug = ${q(l.from_slug)} and t.slug = ${q(l.to_slug)}\n  on conflict do nothing;`,
);

writeFileSync(
  out,
  `-- GENERATED by packages/content/scripts/generate-issuances-sql.ts. Do not edit by hand.
-- Seed issuances are inserted as drafts for CPA review; existing rows are left untouched.

insert into public.issuances (slug, type, number, title, date_issued, effectivity_date, tax_types, topics, summary_plain, status, source_url, needs_verification) values
${rows.join(",\n")}
on conflict (type, number) do nothing;

${links.join("\n")}
`,
);
console.log(`Wrote ${out}`);
