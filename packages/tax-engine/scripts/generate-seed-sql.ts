/**
 * Generates supabase/seed.sql from the tax-engine data files, so the database and
 * the bundled engine data share one source of truth.  Run: pnpm db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { checklistItems, deadlineRules, forms, holidays, registrationSteps, taxRules, validateRules } from "../src";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../supabase/seed.sql");

/** Marks a value to be written as jsonb even if it is a string array. */
class Json {
  constructor(public readonly v: unknown) {}
}

function q(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (v instanceof Json) return `${q(JSON.stringify(v.v))}::jsonb`;
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
    return `array[${v.map(q).join(", ")}]::text[]`;
  }
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insert(table: string, cols: string[], rows: unknown[][], conflict: string): string {
  if (rows.length === 0) return "";
  const values = rows.map((r) => `  (${r.map(q).join(", ")})`).join(",\n");
  const quoted = cols.map((c) => (c === "order" || c === "where" ? `"${c}"` : c));
  const updates = quoted.filter((c) => c !== conflict).map((c) => `${c} = excluded.${c}`).join(", ");
  return `insert into public.${table} (${quoted.join(", ")}) values\n${values}\non conflict (${conflict}) do update set ${updates};\n`;
}

const problems = validateRules(taxRules);
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const sql = [
  "-- GENERATED by packages/tax-engine/scripts/generate-seed-sql.ts. Do not edit by hand.",
  "-- Every row is needs_verification = true until the CPA confirms it (see docs/VERIFY.md).",
  "",
  insert(
    "tax_rules",
    ["id", "rule_key", "tax_type", "taxpayer_category", "value_json", "effective_from", "effective_to", "legal_basis", "source_url", "last_verified_at", "needs_verification", "note"],
    taxRules.map((r) => [r.id, r.rule_key, r.tax_type, r.taxpayer_category, r.value, r.effective_from, r.effective_to, r.legal_basis, r.source_url, r.last_verified_at, r.needs_verification, r.note ?? null]),
    "id",
  ),
  insert(
    "forms",
    ["code", "name", "description", "who_files", "frequency", "filing_channels", "guide_slug", "needs_verification"],
    forms.map((f) => [f.code, f.name, f.description, f.who_files, f.frequency, f.filing_channels, f.guide_slug, f.needs_verification]),
    "code",
  ),
  insert(
    "deadline_rules",
    ["id", "form_code", "title", "frequency", "due_logic_json", "applies_when_json", "filing_channel", "effective_from", "effective_to", "legal_basis", "source_url", "last_verified_at", "needs_verification", "note"],
    deadlineRules.map((r) => [r.id, r.form_code, r.title, r.frequency, r.due_logic, r.applies_when, r.filing_channel, r.effective_from, r.effective_to, r.legal_basis, r.source_url, r.last_verified_at, r.needs_verification, r.note ?? null]),
    "id",
  ),
  insert(
    "holidays",
    ["date", "name", "type", "year", "legal_basis", "needs_verification", "note"],
    holidays.map((h) => [h.date, h.name, h.type, h.year, h.legal_basis, h.needs_verification, h.note ?? null]),
    "date",
  ),
  insert(
    "registration_steps",
    ["id", "business_form", "order", "agency", "title", "summary", "requirements_json", "where", "online_link", "fees_note", "est_days", "legal_basis", "only_if_employees", "needs_verification"],
    registrationSteps.map((s) => [s.id, s.business_form, s.order, s.agency, s.title, s.summary, new Json(s.requirements), s.where, s.online_link, s.fees_note, s.est_days, s.legal_basis, s.only_if_employees ?? false, s.needs_verification]),
    "id",
  ),
  insert(
    "checklist_templates",
    ["id", "title", "frequency"],
    [["monthly", "Monthly checklist", "monthly"], ["quarterly", "Quarterly checklist", "quarterly"], ["annual", "Annual checklist", "annual"], ["one_time", "One-time setup", "one_time"]],
    "id",
  ),
  insert(
    "checklist_items",
    ["id", "template_id", "title", "frequency", "applies_when_json", "form_code", "detail", "months", "quarters", "due_hint", "legal_basis", "needs_verification"],
    checklistItems.map((i) => [i.id, i.frequency, i.title, i.frequency, new Json(i.applies_when), i.form_code, i.detail, i.months ?? null, i.quarters ? `{${i.quarters.join(",")}}` : null, i.due_hint, i.legal_basis, i.needs_verification]),
    "id",
  ),
].join("\n");

writeFileSync(out, sql);
console.log(`Wrote ${out}`);
