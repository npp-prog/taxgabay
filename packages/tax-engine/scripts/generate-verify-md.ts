import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { HOLIDAYS_NOT_SEEDED, deadlineRules, forms, holidays, registrationSteps, taxRules, type Bracket, type DueLogic } from "../src";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../docs/VERIFY.md");

const cell = (s: unknown) => String(s ?? "—").replace(/\|/g, "\\|").replace(/\n/g, " ");
const row = (cols: unknown[]) => `| ${cols.map(cell).join(" | ")} |`;
const pctOrNum = (v: string) => (/^0\.\d+$/.test(v) ? `${Number((Number(v) * 100).toFixed(4))}%` : Number(v).toLocaleString("en-US"));

function describeValue(v: unknown): string {
  if (v && typeof v === "object" && "brackets" in v && Array.isArray((v as { brackets: unknown[] }).brackets)) {
    const bs = (v as { brackets: (Bracket | { over: string; not_over: string | null; amount: string })[] }).brackets;
    return bs
      .map((b) =>
        "amount" in b
          ? `over ${pctOrNum(b.over)}${b.not_over ? ` to ${pctOrNum(b.not_over)}` : ""}: ₱${pctOrNum(b.amount)}`
          : `over ${pctOrNum(b.over)}${b.not_over ? ` to ${pctOrNum(b.not_over)}` : ""}: ₱${pctOrNum(b.base)} + ${Number((Number(b.rate) * 100).toFixed(4))}%`,
      )
      .join("; ");
  }
  if (v && typeof v === "object" && "classes" in v) {
    return (v as { classes: { size: string; from: string; below: string | null }[] }).classes
      .map((c) => `${c.size}: ₱${pctOrNum(c.from)}${c.below ? ` to < ₱${pctOrNum(c.below)}` : "+"}`)
      .join("; ");
  }
  if (v && typeof v === "object") {
    return Object.entries(v as Record<string, string>)
      .map(([k, x]) => `${k} = ${pctOrNum(String(x))}`)
      .join("; ");
  }
  return String(v);
}

function describeDue(d: DueLogic): string {
  switch (d.kind) {
    case "monthly_following": {
      let s = `${d.day}th of following month${d.period_months === "non_quarter_end" ? " (months 1–2 of each quarter only)" : ""}`;
      if (d.efps_days) s += `; eFPS: ${Object.entries(d.efps_days).map(([g, n]) => `${g}=${n}th`).join(", ")}`;
      if (d.exceptions) s += `; exceptions: ${d.exceptions.map((e) => `period month ${e.period_month} → day ${e.day} of +${e.month_offset} month`).join(", ")}`;
      return s;
    }
    case "quarterly":
      return `Q${d.quarters.join(",Q")} (${d.quarter_basis === "calendar" ? "calendar" : "taxable-year"} quarters): ${
        d.days_after !== undefined ? `${d.days_after} days after quarter end` : `day ${d.day} of month +${d.month_offset} after quarter end`
      }`;
    case "annual":
      return `${d.year_basis === "calendar" ? "Calendar" : "Taxable"} year: day ${d.day} of month +${d.month_offset} after year end`;
    case "event":
      return `${d.days_after_event} days after ${d.event}`;
  }
}

const low = [
  ...taxRules.filter((r) => r.note?.includes("LOW CONFIDENCE")).map((r) => `- **${r.id}** — ${r.note}`),
  ...holidays.filter((h) => h.note?.includes("LOW CONFIDENCE")).map((h) => `- **Holiday ${h.date} ${h.name}** — ${h.note}`),
];

