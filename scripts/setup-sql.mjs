// Concatenates migrations and seeds into supabase/setup-all.sql for a one-paste setup.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const root = join(import.meta.dirname, "..", "supabase");
const parts = [...readdirSync(join(root, "migrations")).filter((f) => f.endsWith(".sql")).sort().map((f) => `migrations/${f}`), "seed.sql", "seed-issuances.sql"];
let out = "-- TaxGabay: the whole database in one file (Supabase → SQL Editor → paste → Run).\n-- GENERATED by `pnpm db:setup-sql` from supabase/migrations, seed.sql and seed-issuances.sql. Run it once, on a new project.\n";
for (const p of parts) out += `\n-- ======================================================================\n-- supabase/${p}\n-- ======================================================================\n` + readFileSync(join(root, p), "utf8");
writeFileSync(join(root, "setup-all.sql"), out);
console.log(`Wrote supabase/setup-all.sql (${parts.length} files)`);
